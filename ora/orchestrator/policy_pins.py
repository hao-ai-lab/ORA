"""Path-only policy assets: which assets this tree composes, and stripping their inline pins.

Maintained assets name each other by path; ``policy.lock`` carries integrity
and each loader hashes the bytes it reads (``agent/composition/locked_assets``).
An asset this tree composes is one a loader here can reach without a refusal:

- every registered ToolSurface manifest (``PROFILE_CATALOG``);
- every context profile under ``ora/policy/environments``;
- the selectable baseline catalogs (``BASELINE_CATALOGS``: default and maintained);
- the maintained task-contract registries, the RoboDojo layout catalog and the
  contract appendices it names;
- the embodiment descriptors those surfaces and profiles bind, the wording
  reviews the profiles bind, and the ARX descriptor the RoboDojo embodiment
  activation compiles.

Anything else keeps its inline pins.

``ora lock --strip-pins`` rewrites the composable assets to the
path-only form and regenerates ``policy.lock``; with ``--check`` it lists what
it would change and exits 1. It is idempotent and re-runnable after assets are
added or deleted. A pin a loader used to verify is checked against the bytes
before it is removed: a stale pin stops the run instead of reviving an asset
against bytes it never named.

Descriptor provenance: a repository source (``local_path``) keeps its
path and drops its ``revision`` and ``sha256``; the RunPlan's source commit
identifies those bytes. A wording review drops ``descriptor_sha256`` and attests
the card text by ``card_sha256`` alone. Each compiled card manifest
(``compiled-v*/manifest.json``, generated by ``write_compiled_card``) is
regenerated from its descriptor's path-only bytes; the card itself must not
change. Human-review pins (``card_sha256``, task-contract layer-text hashes)
and external identities stay.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Iterator, Mapping

#: Manifest provenance keys that pin another asset (a predecessor manifest or
#: its composition, an in-repo upstream copy or prompt). Provenance is never
#: verified; the predecessor is named by ``derived_from``/``source_profile``.
PROVENANCE_PIN_KEYS = (
    "source_manifest_sha256", "source_composition_sha256",
    "profile_manifest_file_sha256", "prompt_sha256",
)
_COMPONENT_GROUPS = ("supplementary_definitions", "source_artifacts", "components")
#: Keys a repository provenance source no longer carries.
REPOSITORY_SOURCE_PIN_KEYS = ("revision", "sha256")
EMBODIMENTS = "ora/policy/embodiments"


class StalePinError(RuntimeError):
    """An inline pin a loader verified no longer matches its asset's bytes."""


@dataclass(frozen=True)
class Pin:
    """One inline pin the strip removes."""

    key: str
    value: str
    target: str | None
    verified: bool
    reference_key: str | None = None
    reference: str | None = None


@dataclass
class Strip:
    """The planned rewrite of one asset."""

    path: str
    kind: str
    pins: list[Pin] = field(default_factory=list)
    text: str | None = None


def _checkout_relative(path: Path) -> str | None:
    checkout = Path(__file__).resolve().parents[2]
    resolved = Path(path).resolve()
    return resolved.relative_to(checkout).as_posix() if resolved.is_relative_to(checkout) else None


def composable_pin_holders(root: Path) -> dict[str, str]:
    """``{path: kind}`` of every asset this tree composes that could hold an asset pin."""

    from ora.agent.composition.baseline import BASELINE_CATALOGS
    from ora.agent.composition.profile_catalog import PROFILE_CATALOG
    from ora.agent.composition.robodojo_layout_compatibility import (
        LAYOUT_CATALOG_PATH, LAYOUT_PORTABILITY_PATH,
    )
    from ora.agent.composition.robodojo_task_contract import REGISTRY_PATH
    from ora.agent.composition.task_contract import REGISTRIES

    root = Path(root)
    holders: dict[str, str] = {}
    embodiments: dict[str, str] = {}
    for manifest in PROFILE_CATALOG.values():
        relative = _checkout_relative(manifest)
        if relative is not None and (root / relative).is_file():
            holders[relative] = "tool_surface_manifest"
            geometry = (json.loads((root / relative).read_text(encoding="utf-8")).get("view_config") or {}).get(
                "public_geometry_descriptor")
            if isinstance(geometry, str):
                embodiments.setdefault(geometry, "geometry_descriptor")
    for relative, profile in _context_profiles(root):
        holders[relative] = "context_profile"
        binding = profile.get("compiled_embodiment")
        if isinstance(binding, Mapping) and isinstance(binding.get("descriptor"), str):
            embodiments[binding["descriptor"]] = "embodiment_descriptor"
        if isinstance(binding, Mapping) and isinstance(binding.get("review"), str):
            embodiments[binding["review"]] = "embodiment_wording_review"
    embodiments[_activation_descriptor()] = "embodiment_descriptor"
    holders.update(embodiments)
    for catalog in BASELINE_CATALOGS.values():
        holders[catalog] = "baseline_catalog"
    for registry in REGISTRIES.values():
        holders[registry] = "robotwin_task_contract_registry"
    holders[REGISTRY_PATH] = "robodojo_task_contract_registry"
    holders[LAYOUT_CATALOG_PATH] = "robodojo_layout_catalog"
    for task in json.loads((root / LAYOUT_CATALOG_PATH).read_text(encoding="utf-8"))["tasks"].values():
        appendix = task.get("contract_appendix")
        if appendix is not None:
            holders[appendix if isinstance(appendix, str) else appendix["path"]] = "robodojo_layout_appendix"
    if (root / LAYOUT_PORTABILITY_PATH).is_file():
        holders[LAYOUT_PORTABILITY_PATH] = "robodojo_layout_portability"
    return dict(sorted(holders.items()))


def _context_profiles(root: Path) -> Iterator[tuple[str, Mapping[str, Any]]]:
    """``(path, profile)`` of every context profile in the tree."""

    for path in sorted((Path(root) / "ora/policy/environments").glob("*/context-profile-*.json")):
        yield path.relative_to(root).as_posix(), json.loads(path.read_text(encoding="utf-8"))


def _activation_descriptor() -> str:
    """The ARX descriptor the RoboDojo embodiment activation compiles and binds."""

    from ora.orchestrator.robodojo_embodiment import DESCRIPTOR_PATH, PROJECT_ROOT

    return DESCRIPTOR_PATH.relative_to(PROJECT_ROOT).as_posix()


def review_targets(root: Path) -> dict[str, str]:
    """``{wording review: descriptor}`` as the context profiles bind them."""

    targets: dict[str, str] = {}
    for _relative, profile in _context_profiles(root):
        compiled = profile.get("compiled_embodiment")
        if (isinstance(compiled, Mapping) and isinstance(compiled.get("review"), str)
                and isinstance(compiled.get("descriptor"), str)):
            targets[compiled["review"]] = compiled["descriptor"]
    return targets


# ---- planning: which pins each kind holds ----------------------------------------

def _binding(value: Any, inner: str) -> bool:
    return (isinstance(value, Mapping) and set(value) == {inner, "sha256"}
            and isinstance(value[inner], str) and isinstance(value["sha256"], str))


def _manifest_pins(path: str, value: Mapping[str, Any]) -> Iterator[tuple[str, Any, str, Pin]]:
    """(container key path, container, key, pin) for each manifest pin."""

    directory = Path(path).parent
    specs: list[tuple[str, Any, Any]] = []
    for key in ("base_definitions", "additional_definitions"):
        specs.append((key, value, key))
    for group in _COMPONENT_GROUPS:
        container = value.get(group)
        keys = range(len(container)) if isinstance(container, list) else (container or {})
        specs.extend((f"{group}/{key}", container, key) for key in keys)
    for location, container, key in specs:
        spec = container.get(key) if isinstance(container, Mapping) else container[key]
        if _binding(spec, "ref"):
            target = os.path.normpath((directory / spec["ref"]).as_posix())
            yield location, container, key, Pin(f"{location}/sha256", spec["sha256"], target, True,
                                                 "ref", spec["ref"])
    view = value.get("view_config")
    if isinstance(view, Mapping) and _binding(view.get("public_geometry_descriptor"), "path"):
        spec = view["public_geometry_descriptor"]
        yield ("view_config/public_geometry_descriptor", view, "public_geometry_descriptor",
               Pin("view_config/public_geometry_descriptor/sha256", spec["sha256"], spec["path"], True,
                   "path", spec["path"]))
    provenance = value.get("provenance")
    if isinstance(provenance, Mapping):
        for key in PROVENANCE_PIN_KEYS:
            if isinstance(provenance.get(key), str):
                yield "provenance", provenance, key, Pin(f"provenance/{key}", provenance[key], None, False)


def _path_bindings(container: Any, keys: tuple[str, ...], location: str,
                   *, keep_path_object: bool = False) -> Iterator[tuple[str, Any, str, Pin]]:
    if not isinstance(container, Mapping):
        return
    for key in keys:
        spec = container.get(key)
        if _binding(spec, "path"):
            where = f"{location}/{key}" if location else key
            yield (where, container, key,
                   Pin(f"{where}/sha256", spec["sha256"], spec["path"], True,
                       None if keep_path_object else "path", spec["path"]))


def _descriptor_pins(kind: str, value: Mapping[str, Any]) -> Iterator[tuple[str, Any, str, Pin]]:
    """The ``revision``/``sha256`` of each repository provenance source.

    A loader audits the provenance of an ``embodiment_descriptor`` (a context
    profile's card, the RoboDojo activation), so its byte pins are checked
    before removal. A ``geometry_descriptor`` is bound only for its geometry;
    no loader here reads its provenance, so its pins were never verified.
    """

    sources = (value.get("provenance") or {}).get("sources")
    for index, source in enumerate(sources if isinstance(sources, list) else []):
        if not isinstance(source, Mapping) or not isinstance(source.get("local_path"), str):
            continue
        location = f"provenance/sources/{index}"
        for key in REPOSITORY_SOURCE_PIN_KEYS:
            if isinstance(source.get(key), str):
                verified = key == "sha256" and kind == "embodiment_descriptor"
                yield location, source, key, Pin(
                    f"{location}/{key}", source[key], source["local_path"] if verified else None, verified)


def _planned_pins(path: str, kind: str, value: Any,
                  targets: Mapping[str, str] | None = None) -> list[tuple[str, Any, str, Pin]]:
    if kind == "tool_surface_manifest":
        return list(_manifest_pins(path, value))
    found: list[tuple[str, Any, str, Pin]] = []
    if kind in ("embodiment_descriptor", "geometry_descriptor"):
        found += _descriptor_pins(kind, value)
    elif kind == "embodiment_wording_review":
        if isinstance(value.get("descriptor_sha256"), str):
            # The raw bytes of the descriptor its profile binds beside it.
            target = (targets or {}).get(path)
            found.append(("", value, "descriptor_sha256",
                          Pin("descriptor_sha256", value["descriptor_sha256"], target, target is not None)))
    elif kind == "context_profile":
        found += _path_bindings(value.get("compiled_embodiment"), ("descriptor", "review"), "compiled_embodiment")
    elif kind == "baseline_catalog":
        for name, instance in (value.get("instances") or {}).items():
            found += _path_bindings(instance.get("runtime"), ("motion_profile", "control_profile"),
                                    f"instances/{name}/runtime")
    elif kind == "robotwin_task_contract_registry":
        for task, entry in value["tasks"].items():
            found += _path_bindings(entry, ("semantic_review",), f"tasks/{task}")
    elif kind == "robodojo_task_contract_registry":
        for task, entry in value["tasks"].items():
            if isinstance(entry.get("record_sha256"), str):
                found.append((f"tasks/{task}", entry, "record_sha256",
                              Pin(f"tasks/{task}/record_sha256", entry["record_sha256"], entry["record"], True)))
    elif kind == "robodojo_layout_catalog":
        for task, entry in value["tasks"].items():
            found += _path_bindings(entry, ("contract_appendix",), f"tasks/{task}")
    elif kind == "robodojo_layout_appendix":
        found += _path_bindings(value, ("contract_record",), "")
    return found


def _strip_value(path: str, kind: str, value: Any,
                 targets: Mapping[str, str] | None = None) -> tuple[Any, list[Pin]]:
    """Apply the strip to a parsed copy; return it with the pins removed."""

    import copy

    value = copy.deepcopy(value)
    pins = []
    for _location, container, key, pin in _planned_pins(path, kind, value, targets):
        pins.append(pin)
        if pin.reference_key is not None:
            container[key] = pin.reference
        elif key in container and isinstance(container[key], Mapping):
            container[key] = {k: v for k, v in container[key].items() if k != "sha256"}
        else:
            del container[key]
    return value, pins


# ---- textual rewrite that keeps each file's own formatting ------------------------

def _rewrite_text(text: str, pins: list[Pin]) -> str:
    for pin in pins:
        hexvalue = re.escape(pin.value)
        if pin.reference_key is not None:
            reference = re.escape(json.dumps(pin.reference, ensure_ascii=False))
            inner = re.escape(json.dumps(pin.reference_key))
            pattern = (rf'\{{\s*{inner}\s*:\s*{reference}\s*,\s*"sha256"\s*:\s*"{hexvalue}"\s*\}}'
                       rf'|\{{\s*"sha256"\s*:\s*"{hexvalue}"\s*,\s*{inner}\s*:\s*{reference}\s*\}}')
            text, count = re.subn(pattern, lambda _m, r=json.dumps(pin.reference, ensure_ascii=False): r, text, count=1)
        else:
            key = re.escape(json.dumps(pin.key.rsplit("/", 1)[-1]))
            member = rf'{key}\s*:\s*"{hexvalue}"'
            count = 0
            for pattern in (rf',\s*{member}', rf'{member}\s*,\s*', member):
                text, count = re.subn(pattern, "", text, count=1)
                if count:
                    break
        if count != 1:
            raise StalePinError(f"cannot locate the inline pin {pin.key} in the asset text")
    return text


def _stale(root: Path, path: str, pins: list[Pin]) -> list[str]:
    stale = []
    for pin in pins:
        if not pin.verified:
            continue
        target = (Path(root) / pin.target).resolve()
        actual = hashlib.sha256(target.read_bytes()).hexdigest() if target.is_file() else None
        if actual != pin.value:
            stale.append(f"{path}: {pin.key} names {pin.target} at {pin.value}, bytes are {actual}")
    return stale


def strip_asset(root: Path, path: str, kind: str) -> tuple[Any, list[Pin]]:
    """The path-only form of one asset, after checking every pin a loader verified.

    Also how a composition-only test reads a frozen asset with this tree's
    loaders: it composes this verified copy, never the inline form.
    """

    value = json.loads((Path(root) / path).read_text(encoding="utf-8"))
    stripped, pins = _strip_value(path, kind, value)
    stale = _stale(root, path, pins)
    if stale:
        raise StalePinError("stale inline pins:\n" + "\n".join(stale))
    return stripped, pins


def path_only_descriptor(value: Mapping[str, Any]) -> dict[str, Any]:
    """A descriptor with each repository source named by path only; no pin is checked.

    A frozen descriptor keeps its byte pins in place: they held at the commit it
    composes from, not against this tree. A composition-only test that renders
    its card with this tree's code reads this copy; the card omits provenance,
    so the text is the one the frozen descriptor compiled.
    """

    return _strip_value("", "geometry_descriptor", value)[0]


def _generated_card_manifests(root: Path, rewritten: Mapping[str, str]) -> list[Strip]:
    """Regenerate each compiled card manifest that differs from its descriptor's output.

    A manifest names its descriptor by ``descriptor_id`` within its embodiment
    directory. ``rewritten`` holds the path-only text of descriptors this strip
    rewrites; the others are read as they are. The card must not change.
    """

    from ora.agent.composition.embodiment import EmbodimentDescriptorError, compiled_card_files

    plans: list[Strip] = []
    for manifest in sorted((root / EMBODIMENTS).glob("*/compiled-v*/manifest.json")):
        relative = manifest.relative_to(root).as_posix()
        recorded = json.loads(manifest.read_text(encoding="utf-8"))
        named = [path for path in sorted(manifest.parent.parent.glob("descriptor-*.json"))
                 if json.loads(path.read_text(encoding="utf-8")).get("descriptor_id") == recorded.get("descriptor_id")]
        if len(named) != 1:
            raise StalePinError(f"{relative}: descriptor_id {recorded.get('descriptor_id')!r} names "
                                f"{len(named)} descriptors in its embodiment directory")
        descriptor = named[0].relative_to(root).as_posix()
        text = rewritten.get(descriptor)
        data = text.encode("utf-8") if text is not None else (root / descriptor).read_bytes()
        try:
            card, _manifest, manifest_text = compiled_card_files(data, project_root=root)
        except EmbodimentDescriptorError as exc:
            raise StalePinError(f"{relative}: cannot compile {descriptor}: {exc}") from exc
        if card != (manifest.parent / "manual.md").read_text(encoding="utf-8"):
            raise StalePinError(f"{relative}: {descriptor} no longer compiles {manifest.parent.name}/manual.md")
        if manifest_text != manifest.read_text(encoding="utf-8"):
            plans.append(Strip(path=relative, kind="generated_card_manifest", text=manifest_text))
    return plans


def plan_strip(root: Path) -> list[Strip]:
    """Every composable asset that still holds an inline asset pin, with its rewrite.

    It ends with the compiled card manifests whose descriptors that rewrite
    changes (``generated_card_manifest``, regenerated, no pins).
    """

    root = Path(root)
    plans: list[Strip] = []
    stale: list[str] = []
    targets = review_targets(root)
    for path, kind in composable_pin_holders(root).items():
        text = (root / path).read_text(encoding="utf-8")
        stripped, pins = _strip_value(path, kind, json.loads(text), targets)
        if not pins:
            continue
        stale += _stale(root, path, pins)
        new_text = _rewrite_text(text, pins)
        if json.loads(new_text) != stripped:
            raise StalePinError(f"{path}: the text rewrite does not match the planned path-only form")
        plans.append(Strip(path=path, kind=kind, pins=pins, text=new_text))
    if stale:
        raise StalePinError("stale inline pins; resolve them before stripping:\n" + "\n".join(stale))
    rewritten = {plan.path: plan.text for plan in plans
                 if plan.kind in ("embodiment_descriptor", "geometry_descriptor")}
    return plans + _generated_card_manifests(root, rewritten)


def apply_strip(root: Path, plans: list[Strip]) -> None:
    for plan in plans:
        target = Path(root) / plan.path
        temporary = target.with_name(target.name + ".tmp")
        temporary.write_text(plan.text, encoding="utf-8")
        temporary.replace(target)


# ---- what stays inline: the ratchet's classification ----------------------------

#: (asset-path pattern, key-path pattern, kind). The first match classifies a
#: literal; ``frozen`` is everything outside the composable closure.
REMAINING_KINDS: tuple[tuple[str, str, str], ...] = (
    # Human-review pins: a person (or source review) accepted this exact text.
    (r"/context-profile-[^/]+\.json$", r"^(compiled|source_bound)_embodiment/card_sha256$", "human_review"),
    (r"/wording-review-[^/]+\.json$", r"^card_sha256$", "human_review"),
    (r"/robotwin/task-contracts/registry-v\d+\.json$", r"^tasks/[^/]+/sha256$", "human_review"),
    # A RoboDojo review record names its frozen predecessor (record and layer
    # text) exactly; frozen registries v4-v6 pin these shared records' bytes.
    (r"/robodojo/task-contracts/reviews/[^/]+\.json$",
     r"^(contract_layer/sha256|supersedes/(layer|record)_sha256)$", "human_review"),
    # Generated by write_compiled_card from its descriptor; plan_strip regenerates it.
    (r"/compiled-v\d+/manifest\.json$", r".", "generated_card_manifest"),
    # External identities: bytes outside this repository. A descriptor source
    # with a local_path is a repository source and never matches.
    (r"/descriptor-[^/]+\.json$", r"^provenance/sources/\d+/sha256$", "external"),
    (r"/robotwin/task-contracts/registry-v\d+\.json$", r"^tasks/[^/]+/check_success_sha256$", "external"),
    (r"/task-contracts/reviews/[^/]+\.json$",
     r"^(source_dependencies|evaluator_dependencies|evidence)/\d+/sha256$"
     r"|^source/|^layout/layout_sha256$|^notes/\d+$"
     r"|^(layouts/\d+/|reviewed_layout/layout_sha256$)", "external"),
    (r"/robodojo-layout-pools-v\d+\.json$", r"^tasks/[^/]+/pool/\d+/layout_sha256$", "external"),
    # The single-layout portability table repeats each audited
    # record's reviewed layer hash and pins the official layout bytes it audited.
    (r"/robodojo/task-contracts/layout-portability-v\d+\.json$", r"^tasks/[^/]+/contract_layer_sha256$",
     "human_review"),
    (r"/robodojo/task-contracts/layout-portability-v\d+\.json$", r"^tasks/[^/]+/layouts/\d+/layout_sha256$",
     "external"),
    (r"/control-profile-v\d+\.json$", r"^source_binding/", "external"),
)


def _literals(value: Any, prefix: str = "") -> Iterator[tuple[str, str]]:
    if isinstance(value, Mapping):
        for key, item in value.items():
            yield from _literals(item, f"{prefix}{key}" if not prefix else f"{prefix}/{key}")
    elif isinstance(value, list):
        for index, item in enumerate(value):
            yield from _literals(item, f"{prefix}/{index}" if prefix else str(index))
    elif isinstance(value, str):
        for match in re.finditer(r"(?<![0-9a-fA-F])[0-9a-f]{64}(?![0-9a-fA-F])", value):
            yield prefix, match.group(0)


def classify(path: str, key: str, value: Any = None) -> str | None:
    """The kind of the literal at ``key`` of asset ``path`` (parsed as ``value``).

    A ``sha256`` of a descriptor's repository source is never classified: such
    a pin is ``frozen`` outside the composable closure and refused inside it.
    """

    source = re.fullmatch(r"provenance/sources/(\d+)/sha256", key)
    if source is not None and isinstance(value, Mapping):
        sources = (value.get("provenance") or {}).get("sources") or []
        index = int(source.group(1))
        if index < len(sources) and isinstance(sources[index], Mapping) and "local_path" in sources[index]:
            return None
    for path_pattern, key_pattern, kind in REMAINING_KINDS:
        if re.search(path_pattern, path) and re.search(key_pattern, key):
            return kind
    return None


def composable_closure(root: Path) -> dict[str, str]:
    """Every locked asset a composition in this tree reads, with the reason."""

    from ora.agent.composition.locked_assets import locked_paths

    root = Path(root)
    locked = locked_paths(root) or frozenset()
    seen: dict[str, str] = {}
    pending: list[tuple[str, str]] = [(path, kind) for path, kind in composable_pin_holders(root).items()]

    tree = root.resolve()

    def follow(reference: Any, base: str | None, why: str) -> None:
        if isinstance(reference, Mapping):
            reference = reference.get("ref", reference.get("path"))
        if not isinstance(reference, str):
            return
        target = ((tree / base).parent if base else tree).joinpath(reference).resolve()
        if target.is_relative_to(tree):
            pending.append((target.relative_to(tree).as_posix(), why))

    while pending:
        path, why = pending.pop()
        if path in seen or path not in locked:
            continue
        seen[path] = why
        if not path.endswith(".json"):
            continue
        value = json.loads((root / path).read_text(encoding="utf-8"))
        if not isinstance(value, Mapping):
            continue
        schema = value.get("schema", "")
        if schema == "ora.tool-surface-profile.v1":
            for key in ("base_definitions", "additional_definitions"):
                follow(value.get(key), path, "component")
            for group in _COMPONENT_GROUPS:
                container = value.get(group) or {}
                for item in (container if isinstance(container, list) else container.values()):
                    follow(item, path, "component")
            follow((value.get("view_config") or {}).get("public_geometry_descriptor"), None, "descriptor")
        elif schema == "ora.environment-prompt-profile.v1":
            for key in ("descriptor", "review"):
                follow((value.get("compiled_embodiment") or {}).get(key), None, f"compiled_embodiment {key}")
        elif "embodiment-descriptor" in schema:
            for source in (value.get("provenance") or {}).get("sources", []):
                follow(source.get("local_path"), None, "descriptor provenance")
        elif schema == "ora.native-baseline.v1":
            for instance in value["instances"].values():
                for key in ("motion_profile", "control_profile"):
                    follow(instance["runtime"].get(key), None, "runtime profile")
        elif schema == "ora.robotwin-task-contract-registry.v1":
            for entry in value["tasks"].values():
                follow(entry.get("semantic_review"), None, "semantic review")
        elif schema == "ora.robodojo-task-contract-registry.v1":
            for entry in value["tasks"].values():
                follow(entry.get("record"), None, "task-contract record")
        elif schema == "ora.robodojo-layout-pools.v1":
            for entry in value["tasks"].values():
                follow(entry.get("contract_appendix"), None, "contract appendix")
        elif schema == "ora.robodojo-task-contract-layout-portability.v1":
            for entry in value["tasks"].values():
                follow(entry.get("record"), None, "task-contract record")
    return dict(sorted(seen.items()))


def remaining_literals(root: Path) -> list[dict[str, str]]:
    """Every 64-hex literal left in a locked JSON asset, with its kind.

    A literal ``REMAINING_KINDS`` names is ``human_review``,
    ``generated_card_manifest`` or ``external`` wherever it sits. Any other
    literal -- a repository-source pin of a descriptor included -- is ``frozen``
    in an asset this tree does not compose and ``unclassified`` in one it does,
    which the ratchet refuses.
    ``asset_pin`` names the locked asset whose current sha256 the literal equals.
    """

    from ora.agent.composition.locked_assets import locked_paths

    root = Path(root)
    closure = composable_closure(root)
    locked = sorted(locked_paths(root) or ())
    digests = {hashlib.sha256((root / path).read_bytes()).hexdigest(): path for path in locked}
    rows = []
    for path in locked:
        if not path.endswith(".json"):
            continue
        value = json.loads((root / path).read_text(encoding="utf-8"))
        for key, literal in _literals(value):
            kind = classify(path, key, value) or ("unclassified" if path in closure else "frozen")
            rows.append({"path": path, "key": key, "kind": kind, "composed": path in closure,
                         "asset_pin": digests.get(literal, "")})
    return rows


def command_strip(root: Path, *, check: bool, write_lock: Callable[[Path], Path]) -> int:
    """``ora lock --strip-pins [--check]``."""

    try:
        plans = plan_strip(root)
    except StalePinError as exc:
        print(str(exc))
        return 1
    count = sum(len(plan.pins) for plan in plans)
    stripped = [plan for plan in plans if plan.kind != "generated_card_manifest"]
    for plan in plans:
        if plan.kind == "generated_card_manifest":
            print(f"{'would regenerate' if check else 'regenerated'}        {plan.path}")
        else:
            print(f"{'would strip' if check else 'stripped'} {len(plan.pins):4d} pins  {plan.path}")
    regenerated = len(plans) - len(stripped)
    if check:
        print(f"{count} inline pins in {len(stripped)} composable assets, "
              f"{regenerated} compiled card manifests to regenerate" if plans
              else "every composable asset is path-only")
        return 1 if plans else 0
    apply_strip(root, plans)
    path = write_lock(root)
    print(f"stripped {count} inline pins from {len(stripped)} assets, regenerated "
          f"{regenerated} compiled card manifests; wrote {path.name}")
    return 0


