"""The composed tool library under ``ora/policy/composed_tools``.

Layout, one immutable directory per tool version::

    composed_tools/<name>/<version>/tool.star           declaration + body
    composed_tools/<name>/<version>/compiled/<arm_profile>.json

``compiled/`` is generated by ``python -m ora.agent.tools.composed
compile`` and committed; the static checks fail when it no longer matches a
fresh compile of ``tool.star`` against the tunable table.

Any directory with the same ``<name>/<version>/tool.star`` layout is a library
root too: a practice agent keeps its task tools in its own workspace and a
surface binds them by absolute path and sha256. A ``tool`` stage's
``<name>/c<n>`` resolves in the root of the tool that names it first, then in
this library (:func:`resolve_tool`); :func:`nested_closure` pins every tool a
binding can reach.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from . import sdk
from .compiler import compiled_identity
from .declaration import Declaration, parse_declaration
from .starlark_runtime import StarlarkProgram, StarlarkProgramError, load_program

LIBRARY_ROOT = Path(__file__).resolve().parents[3] / "policy" / "composed_tools"
REPOSITORY_ROOT = LIBRARY_ROOT.parents[2]
SOURCE_NAME = "tool.star"
COMPILED_DIR = "compiled"


class LibraryError(RuntimeError):
    """A library entry is missing, misplaced or out of date."""


@dataclass(frozen=True)
class ComposedTool:
    directory: Path
    source: str
    program: StarlarkProgram
    declaration: Declaration

    @property
    def name(self) -> str:
        return self.declaration.name

    @property
    def version(self) -> str:
        return self.declaration.version

    def compiled_path(self, arm_profile: str) -> Path:
        return self.directory / COMPILED_DIR / f"{arm_profile}.json"

    def compiled(self, arm_profile: str) -> dict[str, Any]:
        """The committed compiled document, checked against this source and its own hash."""

        path = self.compiled_path(arm_profile)
        if not path.is_file():
            raise LibraryError(f"{self.name}/{self.version} has no compiled {arm_profile} document")
        document = json.loads(path.read_text(encoding="utf-8"))
        if document.get("source_sha256") != self.program.digest:
            raise LibraryError(f"{path} was compiled from other source bytes; recompile")
        if compiled_identity(document) != document.get("compiled_sha256"):
            raise LibraryError(f"{path} does not match its compiled_sha256")
        return document


def _relative(path: Path) -> str:
    try:
        return str(path.relative_to(REPOSITORY_ROOT))
    except ValueError:
        return str(path)


def load_source(source: str, *, filename: str) -> tuple[StarlarkProgram, Declaration]:
    """Load one body with the full SDK and parse its ``TOOL`` header."""

    program = load_program(
        source, filename=filename, host=sdk.HOST, pure=sdk.PURE,
        entrypoints=("plan", "execute"), read_globals=("TOOL",),
    )
    return program, parse_declaration(program.globals["TOOL"])


def load_tool(directory: Path) -> ComposedTool:
    path = Path(directory) / SOURCE_NAME
    source = path.read_text(encoding="utf-8")
    try:
        program, declaration = load_source(source, filename=_relative(path))
    except StarlarkProgramError as exc:
        raise LibraryError(f"{_relative(path)}: {exc}") from None
    expected = (path.parent.parent.name, path.parent.name)
    if (declaration.name, declaration.version) != expected:
        raise LibraryError(
            f"{_relative(path)} declares {declaration.name}/{declaration.version} but lives at {'/'.join(expected)}"
        )
    return ComposedTool(path.parent, source, program, declaration)


def resolve_tool(ref: str, *, near: Path | None = None) -> ComposedTool:
    """The tool ``<name>/c<n>`` names: in the library root ``near`` first, then in this library."""

    name, _, version = ref.partition("/")
    for root in ([Path(near)] if near is not None else []) + [LIBRARY_ROOT]:
        directory = root / name / version
        if (directory / SOURCE_NAME).is_file():
            return load_tool(directory)
    raise LibraryError(f"tool stage {ref} is in neither {near} nor the harness library")


def nested_closure(tool: ComposedTool) -> dict[str, ComposedTool]:
    """Every tool ``tool`` reaches through tool stages, by ref; cycles and depth past the cap are errors."""

    from .declaration import MAX_NESTING_DEPTH

    found: dict[str, ComposedTool] = {}

    def visit(current: ComposedTool, depth: int, path: tuple[str, ...]) -> None:
        for item in current.declaration.stages:
            if item.tool is None:
                continue
            if item.tool in path:
                raise LibraryError(f"tool stages form a cycle: {' -> '.join((*path, item.tool))}")
            if depth + 1 > MAX_NESTING_DEPTH:
                raise LibraryError(f"{'/'.join(path[-1:])} nests {item.tool} deeper than {MAX_NESTING_DEPTH} levels")
            nested = found.get(item.tool) or resolve_tool(item.tool, near=current.directory.parent.parent)
            found[item.tool] = nested
            visit(nested, depth + 1, (*path, item.tool))

    visit(tool, 0, (f"{tool.name}/{tool.version}",))
    return found


def tool_directories(root: Path | None = None) -> list[Path]:
    base = Path(root or LIBRARY_ROOT)
    return sorted(path.parent for path in base.glob(f"*/*/{SOURCE_NAME}"))


def load_library(root: Path | None = None) -> dict[tuple[str, str], ComposedTool]:
    tools = [load_tool(directory) for directory in tool_directories(root)]
    return {(tool.name, tool.version): tool for tool in tools}
