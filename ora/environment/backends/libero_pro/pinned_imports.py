"""Bind LIBERO imports and benchmark data to the pinned checkouts.

These helpers moved out of ``session.py`` so that module stays within its size
ratchet; ``session`` re-exports them for ``construction``, ``preview``,
``probe`` and the existing tests. They support no embodiment-descriptor fact:
the Panda descriptors cite the session modules for control, camera and state
semantics, none of which lives here. ``LiberoProError`` and ``_atomic_json``
(defined in ``common``) are imported from ``session`` at call time, the same
way ``construction`` reaches it, so there is no import cycle.
"""

from __future__ import annotations

import importlib
import json
import os
import sys
from pathlib import Path


def _path_is_within(path: Path, root: Path) -> bool:
    resolved = path.expanduser().resolve()
    expected = root.expanduser().resolve()
    return resolved == expected or expected in resolved.parents


def _benchmark_data_binding(
    *, libero_pro_root: Path, data_root: Path, suite: str,
) -> tuple[Path, str]:
    """Resolve the one declared benchmark-data source for a Runtime suite."""

    from ora.environment.benchmarks.libero import LIBERO_BASE_SUITES

    if suite in LIBERO_BASE_SUITES:
        return (
            (libero_pro_root / "libero/libero").resolve(),
            "pinned_libero_pro_code_original_base_suite",
        )
    return data_root.resolve(), "pinned_libero_pro_dataset"


def _prepare_pinned_libero_imports(
    *, libero_pro_root: Path, data_root: Path, runtime_config_root: Path,
    suite: str,
) -> dict[str, str]:
    """Bind imports and public benchmark data to the verified checkouts.

    RLinf's ``pro`` router prefers an installed ``liberopro`` distribution.  The
    pinned LIBERO-Pro checkout in this project deliberately exposes the normal
    ``libero`` package and already contains the Pro suites.  Selecting the
    standard import route is therefore an adapter detail, not a benchmark
    downgrade: suite names and data still come from the pinned Pro repositories.
    """

    from .session import LiberoProError, _atomic_json

    import_root = libero_pro_root.resolve()
    package_root = (import_root / "libero").resolve()
    package_init = package_root / "libero" / "__init__.py"
    # The paired Pro dataset contains Pro BDDL plus four duplicated base-suite
    # init directories, but it does not contain original base-suite BDDL (and
    # omits LIBERO-90 entirely).  Original suite execution therefore binds
    # both BDDL and init states to the exact pinned code checkout; Pro core and
    # robustness suites bind the paired dataset.  Never mix those roots or
    # search user-global paths as a fallback.
    benchmark_data_root, benchmark_data_source = _benchmark_data_binding(
        libero_pro_root=libero_pro_root, data_root=data_root, suite=suite,
    )
    bddl_root = (benchmark_data_root / "bddl_files").resolve()
    init_root = (benchmark_data_root / "init_files").resolve()
    assets_root = (package_root / "libero" / "assets").resolve()
    for name, path in (
        ("LIBERO package", package_init),
        ("LIBERO BDDL root", bddl_root),
        ("LIBERO init-state root", init_root),
        ("LIBERO asset root", assets_root),
    ):
        if not path.exists():
            raise LiberoProError(f"pinned {name} is unavailable: {path}")

    config_root = runtime_config_root.resolve()
    config_root.mkdir(parents=True, exist_ok=True)
    config_path = config_root / "config.yaml"
    shim_root = config_root / "python-shim"
    shim_package = shim_root / "libero"
    shim_package.mkdir(parents=True, exist_ok=True)
    shim_init = shim_package / "__init__.py"
    shim_init.write_text(
        "# Generated by Robot Harness; bind only the verified checkout.\n"
        f"__path__ = [{json.dumps(str(package_root))}]\n",
        encoding="utf-8",
    )
    config = {
        "benchmark_root": str((package_root / "libero").resolve()),
        "bddl_files": str(bddl_root),
        "init_states": str(init_root),
        # No policy or evaluation path consumes demonstrations here.  Bind the
        # optional key to an existing pinned root so LIBERO does not silently
        # consult a user-global dataset location or emit misleading warnings.
        "datasets": str(data_root.resolve()),
        "assets": str(assets_root),
    }
    _atomic_json(config_path, config)  # JSON is valid YAML and avoids global ~/.libero state.

    os.environ["LIBERO_TYPE"] = "standard"
    os.environ["LIBERO_CONFIG_PATH"] = str(config_root)
    os.environ["LIBERO_BDDL_PATH"] = str(bddl_root)
    os.environ["LIBERO_INIT_STATES_PATH"] = str(init_root)
    os.environ["LIBERO_ASSET_ROOT"] = str(assets_root)
    # LIBERO init states are trusted, Git-verified tensor pickles rather than
    # model weights.  PyTorch 2.6 changed torch.load's implicit default and the
    # unmodified pinned LIBERO checkout does not pass weights_only=False.
    os.environ["TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD"] = "1"
    for path in (str(shim_root), str(import_root)):
        if path in sys.path:
            sys.path.remove(path)
        sys.path.insert(0, path)
    inherited_pythonpath = os.environ.get("PYTHONPATH")
    os.environ["PYTHONPATH"] = os.pathsep.join(filter(None, (
        str(shim_root), str(import_root), inherited_pythonpath,
    )))

    loaded = {
        name: module for name, module in sys.modules.items()
        if name == "libero" or name.startswith("libero.")
    }
    for name, module in loaded.items():
        module_path = Path(str(getattr(module, "__file__", "")))
        search_paths = [
            Path(str(path)).resolve()
            for path in getattr(module, "__path__", ())
        ]
        allowed = _path_is_within(module_path, import_root) or (
            name == "libero" and search_paths == [package_root]
        )
        if module_path.is_file() and not allowed:
            raise LiberoProError(
                f"LIBERO module {name} was already imported outside the pinned "
                f"checkout: {module_path}"
            )
    importlib.invalidate_caches()
    libero = importlib.import_module("libero.libero")
    benchmark = importlib.import_module("libero.libero.benchmark")
    for name, module in (("libero.libero", libero), ("libero benchmark", benchmark)):
        module_path = Path(str(getattr(module, "__file__", ""))).resolve()
        if not _path_is_within(module_path, import_root):
            raise LiberoProError(
                f"{name} resolved outside the pinned checkout: {module_path}"
            )
    if Path(str(libero.get_libero_path("bddl_files"))).resolve() != bddl_root:
        raise LiberoProError("LIBERO BDDL path did not bind to the pinned data checkout")
    if Path(str(libero.get_libero_path("init_states"))).resolve() != init_root:
        raise LiberoProError("LIBERO init-state path did not bind to pinned data")
    return {
        "libero_module": str(Path(libero.__file__).resolve()),
        "benchmark_module": str(Path(benchmark.__file__).resolve()),
        "config_file": str(config_path),
        "import_shim": str(shim_init.resolve()),
        "bddl_root": str(bddl_root),
        "init_states_root": str(init_root),
        "benchmark_data_root": str(benchmark_data_root),
        "benchmark_data_source": benchmark_data_source,
        "assets_root": str(assets_root),
        "rlinf_import_variant": "standard_import_of_pinned_libero_pro_checkout",
    }
