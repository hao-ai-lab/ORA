"""A live bundle states a physical quantity as a number with a unit.

The bundle prefix rides the prompt cache, so a constant written there costs
essentially nothing per call: median provider request input on this branch is
~258k tokens against ~1.5k output at ~90% cache read. A quantity the policy has
to derive instead costs reasoning tokens on every turn, and reasoning that
carried hand-derived geometry hit `finish_reason: length` far more often than
reasoning without it. "The jaws are small" is therefore not a cheaper way of
saying "37.35 mm"; it is a more expensive one, paid once per turn forever.

This ratchet fails when a vague magnitude word describes a physical quantity in
a live bundle layer and no number with a unit appears in the same sentence.

Two design choices are load-bearing, both taken from the failure mode that
kills ratchets -- one that fires on things people cannot fix gets raised or
deleted rather than obeyed:

* It scans only *live* bundles, derived mechanically in `_live_bundles` from
  the baselines this tree registers as selectable: the default and the
  maintained ones (`BASELINE_CATALOGS`). Frozen
  baselines compose only from their launch commit; their manuals are inputs to
  sealed experiments, and several of them are regenerated byte-for-byte by
  `render_geometry_card`; a ratchet that demanded edits there would be
  demanding that sealed evidence be rewritten.
* Recorded violations carry a mandatory reason. `test_module_size_ratchet`
  makes a reason mandatory only for a *raised* entry, because reasoning about
  thirty-seven pre-existing files would be busywork. Here the recorded set is
  small enough that every entry can afford the sentence, and the sentence is
  the part a reviewer can disagree with.

Read the live embodiment layer before concluding a constant is missing from it.
It is a *compiled* card, and it already states the controlled-point offset, the
local axes and the finger collision extents as numbers with units, per arm and
per robot. The qualitative wording someone may remember -- "centered between the
jaws at nominal grasp depth", "approach axis" -- survives only in the superseded
hand-written `embodiments/*/manual-v5..v14.md`, which no live bundle binds. The
gap in the live card is narrower and harder: see `RECORDED`.

`VAGUE_MAGNITUDES` is curated from what actually appears in this corpus, not
from a dictionary. Three words were tried and dropped because the evidence said
they cost more than they caught: `close` and `closely` are dominated here by
the verb ("the line the two fingers close along", the `close` gripper
directive), `partial` describes coverage rather than magnitude and its honest
fix is the calibration already delivered with every observation, and `long`
false-matches "as long as". Add a word when a real violation slips past.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[3]

#: Words that stand in for a magnitude. Each is a place where the bundle could
#: have delivered the number and chose an adjective instead.
VAGUE_MAGNITUDES = (
    "adequate", "approximate", "approximately", "big", "bounded", "brief", "coarse",
    "deep", "far", "fast", "few", "fine", "gentle", "heavy", "high", "higher", "large",
    "larger", "loose", "low", "lower", "many", "minimal", "minor", "moderate", "modest",
    "narrow", "near", "nearby", "negligible", "nominal", "reasonable", "roughly",
    "shallow", "short", "shorter", "significant", "slight", "slightly", "slow", "small",
    "smaller", "substantial", "sufficient", "tall", "tapered", "thick", "thin", "tight",
    "tiny", "wide",
)

_TERM = re.compile(r"\b(" + "|".join(sorted(VAGUE_MAGNITUDES, key=len, reverse=True)) + r")\b", re.I)

#: A number -- scalar or bracketed vector -- carrying a unit. The unit
#: alternation is longest-first so `mm` wins over `m`, and the trailing guard
#: stops `m` from matching the start of `metre`. The separator admits a hyphen
#: so `7-DoF` counts.
_QUANTITY = re.compile(
    r"(?:\[[^\[\]]*\d[^\[\]]*\]|[-+]?\d+(?:\.\d+)?)"
    r"[\s-]*"
    r"(?:milliseconds|millimetres|millimetres|micrometres|centimetres|seconds|radians|degrees|"
    r"pixels|metres|meters|radian|degree|second|metre|meter|pixel|DoF|mm|cm|ms|Hz|Nm|rad|deg|px|kg|m|s|N|g|%)"
    r"(?![A-Za-z])"
)

#: Identifier spans. A field or tool name that happens to contain a magnitude
#: word is not prose making a claim, so terms are searched with these removed.
_CODE_SPAN = re.compile(r"`[^`]*`")


def _sentences(text: str) -> list[str]:
    """Split on sentence punctuation only when whitespace follows, so `0.08 m` survives."""
    found = []
    for paragraph in text.split("\n\n"):
        joined = " ".join(paragraph.split())
        found += [part.strip() for part in re.split(r"(?<=[.;!?])\s+", joined) if part.strip()]
    return found


def violations(text: str) -> dict[str, list[str]]:
    """Map each unquantified sentence to the magnitude words it leans on."""
    found = {}
    for sentence in _sentences(text):
        if _QUANTITY.search(sentence):
            continue
        terms = sorted({match.group(1).lower() for match in _TERM.finditer(_CODE_SPAN.sub(" ", sentence))})
        if terms:
            found[sentence] = terms
    return found


def _live_bundles(baseline_ids=None) -> set[str]:
    """Bundles a fresh run can select today: those of the registered selectable baselines.

    Derived rather than listed, so promoting a baseline moves it into scope
    without anyone remembering to edit this file.
    """
    from ora.agent.composition.baseline import BASELINE_CATALOGS, load_native_baseline

    live = set()
    for baseline_id in sorted(BASELINE_CATALOGS if baseline_ids is None else baseline_ids):
        for instance in load_native_baseline(ROOT, baseline_id)["instances"].values():
            native = instance.get("prompt_bundle")
            if native:
                live.add(native)
    return live


def _live_layer_sources(bundles=None) -> set[str]:
    """Every authored Markdown layer a live bundle delivers to the policy."""
    sources = set()
    for bundle in _live_bundles() if bundles is None else bundles:
        for layer in yaml.safe_load((ROOT / bundle).read_text())["layers"].values():
            if not isinstance(layer, dict):
                continue
            value = layer.get("source")
            if isinstance(value, str):
                sources.add(value)
            for item in layer.get("sources") or []:
                sources.add(item)
    return {source for source in sources if source.endswith(".md")}


