def _current() -> dict[tuple[str, str], list[str]]:
    found = {}
    for source in _live_layer_sources():
        for sentence, terms in violations((ROOT / source).read_text()).items():
            found[(source, sentence)] = terms
    return found


def test_a_live_bundle_gives_a_number_where_it_gives_a_magnitude() -> None:
    """Every episode sends the prefix, so an adjective here is billed forever."""

    unrecorded = {key: terms for key, terms in _current().items() if key not in RECORDED}
    assert unrecorded == {}, (
        f"these live bundle sentences name a magnitude with no number and unit: {unrecorded}. "
        "Deliver the quantity from the embodiment descriptor or a bound profile, through the "
        "reader that owns it -- never by typing a plausible value. If it cannot be sourced, "
        "say so in RECORDED with the reason."
    )


def test_a_quantified_sentence_loses_its_place_on_the_list() -> None:
    """A recorded entry that no longer applies must go, or the list stops describing the bundle."""

    current = _current()
    stale = sorted(key for key in RECORDED if key not in current)
    assert stale == [], (
        f"these recorded sentences no longer violate (or no longer exist): {stale}. "
        "Remove them from RECORDED so it keeps describing the bundles that ship."
    )


@pytest.mark.parametrize("key", sorted(RECORDED))
def test_every_recorded_violation_states_why_the_number_is_absent(key) -> None:
    """An entry without a reason is an exemption nobody can argue with."""

    assert str(RECORDED[key]).strip(), (
        f"{key} carries no reason. Say why the quantity cannot be sourced or delivered; "
        "that sentence is the one a reviewer disagrees with."
    )


def test_the_detector_still_fires_on_the_wording_it_was_written_to_catch() -> None:
    """A ratchet whose detector matches nothing passes forever and guards nothing.

    Every sample below is real wording from a superseded manual in this
    repository, kept inline so trimming `VAGUE_MAGNITUDES` fails here loudly
    rather than silently emptying the scan.
    """

    caught = violations(
        "A qualified small pure rotation can use bounded local control.\n\n"
        "`head_camera` is a fixed high overhead view of the central workspace.\n\n"
        "Recovery can try a qualified short retreat before a validated route.\n\n"
        "The global planner searches many IK seeds across wrist configurations.\n\n"
        "It compares two localizations after a slight lift.\n\n"
        "The point centered between the jaws at nominal grasp depth.\n\n"
        "A near-field view resolves it approximately.\n\n"
    )
    assert len(caught) == 7, caught
    assert {term for terms in caught.values() for term in terms} >= {
        "small", "bounded", "high", "short", "many", "slight", "nominal", "near", "approximately",
    }


def test_a_number_with_a_unit_clears_the_same_sentence() -> None:
    """The rule is 'quantify it', not 'never use the word'."""

    assert violations("A converged stage may settle a residual no larger than 10 mm and 5 degrees.") == {}
    assert violations("`right_gripper`: nominal maximum jaw separation 0.08 m.") == {}
    assert violations("Finger collision extent along local approach is [-50.43, 35.57] mm.") == {}
    assert violations("Fixed-base Franka Panda: right 7-DoF arm; parallel-jaw grippers.") == {}
    # The magnitude word must be quantified in its own sentence, not a neighbour's.
    assert violations("Arrival is 5 mm. A small residual is reported truthfully.") != {}


def test_the_scan_covers_the_live_bundles_and_leaves_sealed_ones_alone() -> None:
    """The live/frozen split is the reason this ratchet is obeyable; pin it."""

    live = _live_bundles()
    assert live, "no live bundle resolved; the baseline catalog moved"
    assert all((ROOT / bundle).is_file() for bundle in live), live
    # Every other shipped bundle is out of scope only by name: today that is
    # the explicit `ora local` bundle, which no baseline selects. A bundle
    # added outside the baseline catalogs must be named here to be skipped.
    shipped = {path.relative_to(ROOT).as_posix()
               for path in (ROOT / "ora/policy/prompt_bundles").rglob("*.yaml")}
    assert shipped - live == {"ora/policy/prompt_bundles/local_cpu_v1/libero-panda-native-api.yaml"}
    sources = _live_layer_sources()
    # Each authored layer that reaches the policy as prose is scanned. Both
    # backends of the default select the compute-routed planner and core
    # layers; asserting the predecessors' absence there is what keeps a
    # backend from silently falling back to the advisory wording.
    assert "ora/policy/embodiments/aloha-agilex/manual-public-geometry-v3.md" in sources
    assert "ora/policy/embodiments/franka-panda/manual-public-geometry-v3.md" in sources
    default = _live_layer_sources(_live_bundles({json.loads(
        (ROOT / "tests/data/default-expectations.json").read_text())["default_baseline"]}))
    assert "ora/policy/planners/native/policy-v5.md" in default
    assert "ora/policy/planners/native/policy-v4.md" not in default
    # direct_v4: Native bundles carry core v8 (the round static-facts slot and
    # the delivery trim, revised in place over v7).
    assert "ora/policy/core/evidence-action-loop-v8.md" in default
    assert "ora/policy/core/evidence-action-loop-v7.md" not in default
    assert "ora/policy/core/evidence-action-loop-v6.md" not in default
    assert "ora/policy/core/evidence-action-loop-v5.md" not in default
    # No maintained baseline delivers the predecessor layers any longer.
    assert "ora/policy/planners/native/policy-v4.md" not in sources
    assert "ora/policy/core/evidence-action-loop-v5.md" not in sources
    # A superseded manual bound only by a frozen baseline stays out of scope.
    assert "ora/policy/embodiments/aloha-agilex/manual-v14.md" not in sources
